BEGIN;

CREATE TABLE IF NOT EXISTS categories (
  category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(80) NOT NULL UNIQUE,
  slug VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS products (
  product_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id BIGINT NOT NULL REFERENCES categories(category_id) ON DELETE RESTRICT,
  slug VARCHAR(180) NOT NULL UNIQUE,
  name VARCHAR(160) NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  price NUMERIC(10, 2) NOT NULL CHECK (price >= 0),
  original_price NUMERIC(10, 2) CHECK (original_price IS NULL OR original_price >= price),
  rating NUMERIC(2, 1) NOT NULL DEFAULT 0 CHECK (rating BETWEEN 0 AND 5),
  icon VARCHAR(80) NOT NULL,
  visual_class VARCHAR(30) NOT NULL,
  tag VARCHAR(120) NOT NULL,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS product_variants (
  variant_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id BIGINT NOT NULL REFERENCES products(product_id) ON DELETE RESTRICT,
  name VARCHAR(120) NOT NULL,
  sku VARCHAR(100) NOT NULL UNIQUE,
  price_override NUMERIC(10, 2) CHECK (price_override IS NULL OR price_override >= 0),
  active BOOLEAN NOT NULL DEFAULT TRUE,
  UNIQUE (product_id, name),
  UNIQUE (product_id, variant_id)
);

CREATE TABLE IF NOT EXISTS product_images (
  image_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id BIGINT NOT NULL REFERENCES products(product_id) ON DELETE RESTRICT,
  image_url VARCHAR(500) NOT NULL,
  alt_text VARCHAR(250) NOT NULL,
  sort_order INTEGER NOT NULL DEFAULT 0 CHECK (sort_order >= 0),
  UNIQUE (product_id, image_url),
  UNIQUE (product_id, image_id)
);

CREATE TABLE IF NOT EXISTS variant_images (
  product_id BIGINT NOT NULL,
  variant_id BIGINT NOT NULL REFERENCES product_variants(variant_id) ON DELETE CASCADE,
  image_id BIGINT NOT NULL REFERENCES product_images(image_id) ON DELETE CASCADE,
  sort_order INTEGER NOT NULL DEFAULT 0 CHECK (sort_order >= 0),
  PRIMARY KEY (variant_id, image_id),
  FOREIGN KEY (product_id, variant_id)
    REFERENCES product_variants(product_id, variant_id) ON DELETE CASCADE,
  FOREIGN KEY (product_id, image_id)
    REFERENCES product_images(product_id, image_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS orders (
  order_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  status VARCHAR(30) NOT NULL DEFAULT 'received_demo'
    CHECK (status IN ('received_demo', 'pending', 'confirmed', 'cancelled')),
  total NUMERIC(14, 2) NOT NULL CHECK (total >= 0),
  currency CHAR(3) NOT NULL DEFAULT 'USD',
  is_demo BOOLEAN NOT NULL DEFAULT TRUE CHECK (is_demo = TRUE),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS order_items (
  order_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL REFERENCES orders(order_id) ON DELETE CASCADE,
  product_id BIGINT NOT NULL,
  variant_id BIGINT NOT NULL,
  product_name_snapshot VARCHAR(160) NOT NULL,
  variant_snapshot VARCHAR(120) NOT NULL,
  unit_price NUMERIC(10, 2) NOT NULL CHECK (unit_price >= 0),
  quantity INTEGER NOT NULL CHECK (quantity BETWEEN 1 AND 99),
  FOREIGN KEY (product_id, variant_id)
    REFERENCES product_variants(product_id, variant_id) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS products_category_active_idx ON products(category_id, active);
CREATE INDEX IF NOT EXISTS product_variants_product_active_idx ON product_variants(product_id, active);
CREATE INDEX IF NOT EXISTS product_images_product_order_idx ON product_images(product_id, sort_order);
CREATE INDEX IF NOT EXISTS orders_created_at_idx ON orders(created_at DESC);
CREATE INDEX IF NOT EXISTS order_items_order_idx ON order_items(order_id);

COMMIT;
